CREATE TABLE IF NOT EXISTS users (
    id_pengguna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pengguna VARCHAR(50) NOT NULL UNIQUE,
    nama_lengkap VARCHAR(120) NOT NULL,
    peran VARCHAR(30) NOT NULL DEFAULT 'staff',
    waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS suppliers (
    id_pemasok BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_pemasok VARCHAR(30) NOT NULL UNIQUE,
    nama VARCHAR(120) NOT NULL,
    nama_kontak VARCHAR(120),
    telepon VARCHAR(30),
    alamat TEXT,
    waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    id_produk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    nama VARCHAR(150) NOT NULL,
    kategori VARCHAR(80),
    id_pemasok BIGINT REFERENCES suppliers(id_pemasok) ON DELETE SET NULL,
    satuan VARCHAR(30) NOT NULL DEFAULT 'pcs',
    jumlah_stok NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (jumlah_stok >= 0),
    biaya_satuan NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (biaya_satuan >= 0),
    harga_jual NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (harga_jual >= 0),
    stok_minimum NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (stok_minimum >= 0),
    waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    id_transaksi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_transaksi VARCHAR(50) NOT NULL UNIQUE,
    id_produk BIGINT NOT NULL REFERENCES products(id_produk) ON DELETE RESTRICT,
    id_pemasok BIGINT REFERENCES suppliers(id_pemasok) ON DELETE SET NULL,
    jenis_transaksi VARCHAR(3) NOT NULL CHECK (jenis_transaksi IN ('IN', 'OUT')),
    kuantitas NUMERIC(14, 2) NOT NULL CHECK (kuantitas > 0),
    biaya_satuan NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (biaya_satuan >= 0),
    tanggal_transaksi TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    catatan TEXT,
    UNIQUE (id_transaksi, id_produk)
);

CREATE TABLE IF NOT EXISTS sales_history (
    id_penjualan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi BIGINT NOT NULL UNIQUE,
    id_produk BIGINT NOT NULL,
    kuantitas_terjual NUMERIC(14, 2) NOT NULL CHECK (kuantitas_terjual > 0),
    harga_satuan NUMERIC(14, 2) NOT NULL CHECK (harga_satuan >= 0),
    tanggal_penjualan TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    catatan TEXT,
    FOREIGN KEY (id_transaksi, id_produk)
        REFERENCES transactions(id_transaksi, id_produk)
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS inventory_analysis (
    id_analisis BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produk BIGINT NOT NULL REFERENCES products(id_produk) ON DELETE RESTRICT,
    tanggal_analisis DATE NOT NULL DEFAULT CURRENT_DATE,
    permintaan_tahunan NUMERIC(14, 2) NOT NULL CHECK (permintaan_tahunan > 0),
    biaya_pemesanan NUMERIC(14, 2) NOT NULL CHECK (biaya_pemesanan >= 0),
    biaya_penyimpanan_per_unit_tahun NUMERIC(14, 2) NOT NULL
        CHECK (biaya_penyimpanan_per_unit_tahun > 0),
    rata_rata_permintaan_harian NUMERIC(14, 2) NOT NULL CHECK (rata_rata_permintaan_harian >= 0),
    simpangan_baku_permintaan_harian NUMERIC(14, 2) NOT NULL CHECK (simpangan_baku_permintaan_harian >= 0),
    waktu_tunggu_hari NUMERIC(8, 2) NOT NULL CHECK (waktu_tunggu_hari >= 0),
    skor_z NUMERIC(6, 3) NOT NULL CHECK (skor_z >= 0),
    kuantitas_pemesanan_ekonomis NUMERIC(14, 2) NOT NULL CHECK (kuantitas_pemesanan_ekonomis >= 0),
    stok_pengaman NUMERIC(14, 2) NOT NULL CHECK (stok_pengaman >= 0),
    titik_pemesanan_ulang NUMERIC(14, 2) NOT NULL CHECK (titik_pemesanan_ulang >= 0),
    UNIQUE (id_produk, tanggal_analisis)
);

CREATE INDEX IF NOT EXISTS idx_transactions_product_date
    ON transactions (id_produk, tanggal_transaksi);

CREATE INDEX IF NOT EXISTS idx_sales_history_product_date
    ON sales_history (id_produk, tanggal_penjualan);

CREATE INDEX IF NOT EXISTS idx_inventory_analysis_product_date
    ON inventory_analysis (id_produk, tanggal_analisis);