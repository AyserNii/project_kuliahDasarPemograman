DECLARE
    pemetaan_kolom RECORD;
BEGIN
    FOR pemetaan_kolom IN
        SELECT *
        FROM (VALUES
            ('users', 'user_id', 'id_pengguna'),
            ('users', 'username', 'nama_pengguna'),
            ('users', 'full_name', 'nama_lengkap'),
            ('users', 'role', 'peran'),
            ('users', 'created_at', 'waktu_dibuat'),
            ('suppliers', 'supplier_id', 'id_pemasok'),
            ('suppliers', 'supplier_code', 'kode_pemasok'),
            ('suppliers', 'name', 'nama'),
            ('suppliers', 'contact_name', 'nama_kontak'),
            ('suppliers', 'phone', 'telepon'),
            ('suppliers', 'address', 'alamat'),
            ('suppliers', 'created_at', 'waktu_dibuat'),
            ('products', 'product_id', 'id_produk'),
            ('products', 'name', 'nama'),
            ('products', 'category', 'kategori'),
            ('products', 'supplier_id', 'id_pemasok'),
            ('products', 'unit', 'satuan'),
            ('products', 'stock_quantity', 'jumlah_stok'),
            ('products', 'unit_cost', 'biaya_satuan'),
            ('products', 'selling_price', 'harga_jual'),
            ('products', 'minimum_stock', 'stok_minimum'),
            ('products', 'created_at', 'waktu_dibuat'),
            ('transactions', 'transaction_id', 'id_transaksi'),
            ('transactions', 'transaction_code', 'kode_transaksi'),
            ('transactions', 'product_id', 'id_produk'),
            ('transactions', 'supplier_id', 'id_pemasok'),
            ('transactions', 'transaction_type', 'jenis_transaksi'),
            ('transactions', 'quantity', 'kuantitas'),
            ('transactions', 'unit_cost', 'biaya_satuan'),
            ('transactions', 'transaction_date', 'tanggal_transaksi'),
            ('transactions', 'notes', 'catatan'),
            ('sales_history', 'sales_id', 'id_penjualan'),
            ('sales_history', 'transaction_id', 'id_transaksi'),
            ('sales_history', 'product_id', 'id_produk'),
            ('sales_history', 'quantity_sold', 'kuantitas_terjual'),
            ('sales_history', 'unit_price', 'harga_satuan'),
            ('sales_history', 'sale_date', 'tanggal_penjualan'),
            ('sales_history', 'notes', 'catatan'),
            ('inventory_analysis', 'analysis_id', 'id_analisis'),
            ('inventory_analysis', 'product_id', 'id_produk'),
            ('inventory_analysis', 'analysis_date', 'tanggal_analisis'),
            ('inventory_analysis', 'annual_demand', 'permintaan_tahunan'),
            ('inventory_analysis', 'ordering_cost', 'biaya_pemesanan'),
            ('inventory_analysis', 'holding_cost_per_unit_year', 'biaya_penyimpanan_per_unit_tahun'),
            ('inventory_analysis', 'average_daily_demand', 'rata_rata_permintaan_harian'),
            ('inventory_analysis', 'daily_demand_stddev', 'simpangan_baku_permintaan_harian'),
            ('inventory_analysis', 'lead_time_days', 'waktu_tunggu_hari'),
            ('inventory_analysis', 'z_score', 'skor_z'),
            ('inventory_analysis', 'eoq', 'kuantitas_pemesanan_ekonomis'),
            ('inventory_analysis', 'safety_stock', 'stok_pengaman'),
            ('inventory_analysis', 'reorder_point', 'titik_pemesanan_ulang')
        ) AS daftar_pemetaan(nama_tabel, nama_lama, nama_baru)
    LOOP
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = pemetaan_kolom.nama_tabel
              AND column_name = pemetaan_kolom.nama_lama
        ) AND NOT EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = pemetaan_kolom.nama_tabel
              AND column_name = pemetaan_kolom.nama_baru
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I RENAME COLUMN %I TO %I',
                pemetaan_kolom.nama_tabel,
                pemetaan_kolom.nama_lama,
                pemetaan_kolom.nama_baru
            );
        END IF;
    END LOOP;
END
