CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'staff',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    contact_name VARCHAR(120),
    phone VARCHAR(30),
    address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(80),
    supplier_id BIGINT REFERENCES suppliers(supplier_id) ON DELETE SET NULL,
    unit VARCHAR(30) NOT NULL DEFAULT 'pcs',
    stock_quantity NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    minimum_stock NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_code VARCHAR(50) NOT NULL UNIQUE,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    supplier_id BIGINT REFERENCES suppliers(supplier_id) ON DELETE SET NULL,
    transaction_type VARCHAR(3) NOT NULL CHECK (transaction_type IN ('IN', 'OUT')),
    quantity NUMERIC(14, 2) NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    transaction_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    UNIQUE (transaction_id, product_id)
);

CREATE TABLE IF NOT EXISTS sales_history (
    sales_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL UNIQUE,
    product_id BIGINT NOT NULL,
    quantity_sold NUMERIC(14, 2) NOT NULL CHECK (quantity_sold > 0),
    unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
    sale_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    FOREIGN KEY (transaction_id, product_id)
        REFERENCES transactions(transaction_id, product_id)
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS inventory_analysis (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    analysis_date DATE NOT NULL DEFAULT CURRENT_DATE,
    annual_demand NUMERIC(14, 2) NOT NULL CHECK (annual_demand > 0),
    ordering_cost NUMERIC(14, 2) NOT NULL CHECK (ordering_cost >= 0),
    holding_cost_per_unit_year NUMERIC(14, 2) NOT NULL
        CHECK (holding_cost_per_unit_year > 0),
    average_daily_demand NUMERIC(14, 2) NOT NULL CHECK (average_daily_demand >= 0),
    daily_demand_stddev NUMERIC(14, 2) NOT NULL CHECK (daily_demand_stddev >= 0),
    lead_time_days NUMERIC(8, 2) NOT NULL CHECK (lead_time_days >= 0),
    z_score NUMERIC(6, 3) NOT NULL CHECK (z_score >= 0),
    eoq NUMERIC(14, 2) NOT NULL CHECK (eoq >= 0),
    safety_stock NUMERIC(14, 2) NOT NULL CHECK (safety_stock >= 0),
    reorder_point NUMERIC(14, 2) NOT NULL CHECK (reorder_point >= 0),
    UNIQUE (product_id, analysis_date)
);

CREATE INDEX IF NOT EXISTS idx_transactions_product_date
    ON transactions (product_id, transaction_date);

CREATE INDEX IF NOT EXISTS idx_sales_history_product_date
    ON sales_history (product_id, sale_date);

CREATE INDEX IF NOT EXISTS idx_inventory_analysis_product_date
    ON inventory_analysis (product_id, analysis_date);